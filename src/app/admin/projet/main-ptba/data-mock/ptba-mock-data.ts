// Fonctions utilitaires pour les filtres
export function getUniqueActions(): string[] {
    const actions = new Set(PTBA_ACTIVITIES.map(a => a.action));
    return Array.from(actions).sort();
}

export function getUniqueActeurs(): string[] {
    const acteurs = new Set(PTBA_ACTIVITIES.map(a => a.acteurResponsable));
    return Array.from(acteurs).sort();
}

export function getUniqueSourcesFinancement(): string[] {
    const sources = new Set<string>();
    PTBA_ACTIVITIES.forEach(activity => {
        Object.keys(activity.sourcesFinancement).forEach(source => sources.add(source));
    });
    return Array.from(sources).sort();
}

